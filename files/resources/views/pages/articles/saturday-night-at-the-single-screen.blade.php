    <p>Rain suits the Orpheum. The marquee bulbs — one hundred and forty of them, replaced by hand, by ladder, by a projectionist who has named several — double themselves in the wet street, and for half a block the ordinary world gets color-graded. Inside there is one screen, four hundred and eleven seats, a curtain that still opens, and a line item in the budget for curtain repair that the owner defends every single year.</p>

    <p>The multiplex twenty minutes away has fourteen screens, recliners with heating elements, and an app. It is also, on this particular Saturday, emptier than the Orpheum, which is sold out for a fifty-year-old film most of tonight's audience has already seen. This is no longer considered surprising by anyone in the industry. It is merely considered inconvenient, because it suggests the business spent two decades optimizing the wrong variable.</p>

    <h2>What a room is for</h2>

    <p>The single-screen revival runs on a simple inversion: scarcity as programming. One screen means the theater must choose, and choosing is the product. The Orpheum's calendar is a manifesto — a silent film with live organ on Thursdays, a kids' matinee where talking is legal, a horror night where screaming is encouraged. You do not check what is playing. You check what they picked.</p>

    <blockquote>
        <p>Fourteen screens is a warehouse. One screen is an opinion.</p>
        <cite>The Orpheum's owner, third generation</cite>
    </blockquote>

    <p>The economics work the way the bookstore's do, and the vinyl shop's, and the bakery with one kind of loaf: smaller, denser, communal. Membership covers the mortgage. The bar covers the staff. The tickets, almost incidentally, cover the films. What cannot be itemized is the thing people actually pay for — four hundred strangers agreeing, for two hours, to be in the same story at the same time.</p>

    <h2>The projection booth</h2>

    <p>Up the narrow stairs, the booth holds both futures at once: a laser projector the size of a dorm fridge, and the 1962 carbon-arc machine the owner's grandfather installed, kept runnable for the archival prints that still tour like aging bands. The projectionist patrols between them with the mild vigilance of a lighthouse keeper. Downstairs the curtain opens — on time, by hand — and the room does the thing rooms like this have always done: it goes quiet all at once, four hundred people exhaling into the dark, the rain outside holding its applause until the end.</p>

