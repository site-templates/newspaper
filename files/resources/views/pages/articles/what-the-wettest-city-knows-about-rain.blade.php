    <p>It has been raining for four days, which locals describe as weather and my weather app describes as an emergency. On the Westersingel the canal is up, the bikes are out, and a basketball court two streets over is quietly doing its second job: swallowing three million liters of stormwater beneath the free-throw line. When the sky closes, the court drains over two days into the ground below, and the kids get their game back. Nobody looks up from their coffee.</p>

    <p>This is the Dutch adaptation project in one image. Not the famous part — the surge barriers, the delta works, the engineering of national survival — but the small, municipal, almost domestic part: a city redesigning its ordinary surfaces to make peace with water it once tried only to expel.</p>

    <h2>The sponge doctrine</h2>

    <p>The old doctrine was a pipe: collect the rain, remove the rain, faster, always faster. It fails arithmetically now. A cloudburst that once arrived twice a decade arrives twice a summer, and no pipe network can be economically sized for it. The new doctrine is a sponge: hold the water where it falls, in a thousand small places, and release it slowly. Water squares. Green roofs by the hectare. Parking garages with cisterns in their basements, whose signage displays capacity for both cars and cubic meters.</p>

    <blockquote>
        <p>You cannot win an argument with the sky. You can only give the water somewhere polite to go.</p>
        <cite>A municipal water engineer, translating a Dutch proverb loosely</cite>
    </blockquote>

    <p>The genius of the system is that almost none of it looks like infrastructure. The water square is a skate park fifty-one weeks a year. The retention roof is a meadow with beehives. Resilience here has been disguised as amenity, which turns out to be the trick that makes taxpayers love it — people will vote against a drainage project and for a park every single time, so the city learned to build parks that drain.</p>

    <h2>Exporting the umbrella</h2>

    <p>The delegations arrive weekly now — planners from cities that flooded last year or expect to next. What they come for is less the hardware than the accounting: the Dutch price a storm across decades, tally the avoided damage, and let the numbers make the argument. What they leave with, one visiting engineer told me, is a mental adjustment. She had spent her career asking how to keep water out of the city. The question here is older and calmer: how does the city live with the water it was always going to get?</p>

    <p>By Friday the rain stops. The basketball court surrenders its last meltwater to the soil, the canal settles back between its bricks, and the city forgets, until the next cloudburst, that it is a machine at all. Which is, its designers would say, the entire measure of success.</p>

