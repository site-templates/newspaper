    <p>The blankets arrive by helicopter in rolls the size of felled trees, and after that everything is done by hand. Six people, two weeks, four hundred anchor stones. By the end of June the upper tongue of the glacier is dressed in white geotextile — a patchwork quilt over roughly eight acres of ice, sewn against a summer that gets a little longer every year. From the valley it looks like snow that forgot to melt, which is precisely the idea.</p>

    <p>The fleece works by doing something almost insultingly simple: it is whiter than tired ice. Old glacier surface is grey with dust and rock flour, and grey drinks the sun. The fabric reflects it, and holds a skin of cool air against the surface. Under the blankets, the crew saves between half and two-thirds of the season's melt. The unprotected ice around them drops by two meters in a good summer. In a bad one, three.</p>

    <h2>Eight acres out of eight hundred</h2>

    <p>Everyone involved is disarmingly frank about the arithmetic. The covered patch is around one percent of the glacier. The technique cannot scale — the fabric costs money, the labor costs more, and a glacier is not eight acres, it is a weather system with a body. What the blankets actually protect is more specific: the ice cave that anchors the region's tourism, the ski lift's upper station, a snow bridge that keeps a hiking route open. The crew is not saving the glacier. It is triaging it.</p>

    <blockquote>
        <p>People ask if it works. Wrong question. It works like a tourniquet works. Nobody calls a tourniquet a cure.</p>
        <cite>The crew's foreman, in his fourteenth season</cite>
    </blockquote>

    <p>The foreman started when the job was considered eccentric, borderline theatrical. Now he fields calls from Andorra, Chile, Tajikistan. He tells all of them the same three things: it is cheaper than you hope, it is harder than it looks, and it buys time — nothing else. Time, he adds, is not nothing. Time is the whole currency of adaptation.</p>

    <h2>What the mending is for</h2>

    <p>Spend a week with the crew and the work stops looking like engineering and starts looking like maintenance in the old sense — the way a family keeps a house it knows it cannot keep forever. They mend tears left by winter. They re-seat the anchor stones. They log the melt lines in a notebook whose earlier volumes read like the biography of a shrinking friend.</p>

    <p>The glaciologists who visit each August are careful with their tenses. The glacier will lose this century; the models do not really argue about it anymore. But there is a difference, they point out, between a loss that takes thirty years and one that takes eighty — a difference measured in reservoirs built, in rivers rerouted, in villages that get two generations to decide what comes next instead of half of one. The blankets purchase almost none of that time by themselves. What they purchase is practice: a small, stubborn rehearsal in taking care of a thing on its way out, done publicly, at altitude, every June.</p>

    <p>On the last day of the season the crew walks the seams once more, checking their stitching against the coming winter. Then they hike down, and the mountain keeps their work through the dark months, white on white, invisible until spring.</p>

