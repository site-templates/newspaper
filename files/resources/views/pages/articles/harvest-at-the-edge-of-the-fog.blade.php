    <p>The harvest begins before sunrise, and it makes no sound. On the ridge above the village, forty nets stand face-on to the Pacific like sails that have given up on going anywhere, and the fog walks into them. Droplets too light to fall gather on the mesh, find each other, and finally become heavy enough to obey gravity — down the fibers, into the gutters, through two kilometers of pipe, and into a cistern that was empty four years ago and has not been empty since.</p>

    <p>On a good morning the ridge collects six hundred liters per net. It has not properly rained here since the spring the youngest children cannot remember, and yet the village runs taps, waters two hundred olive trees, and — the detail everyone mentions first — reopened the school it nearly lost when the families began to leave.</p>

    <h2>Engineering at walking pace</h2>

    <p>The technology is almost embarrassingly legible. A net, a frame, a gutter, a tank. No pumps, no power, no firmware. The sophistication hides in the siting: fog is a river with invisible banks, and the difference between a net that drinks and a net that decorates a hillside can be three hundred meters of elevation or one degree of bearing. The village mapped its fog the slow way — a year of walking the ridge with test coupons and a notebook — before ordering a single frame.</p>

    <blockquote>
        <p>Rain is a promise the sky no longer keeps here. Fog is not a promise. Fog is a schedule.</p>
        <cite>The cooperative's founder, who kept the notebook</cite>
    </blockquote>

    <p>The mesh itself has quietly improved — a decade of materials research has roughly doubled what a square meter can catch — but the founders are wary of the word breakthrough. The nets will not green a desert. They serve a narrow, particular geography: coastal mountains, cold currents, six fog months a year. Inside that geography, they are transformative. Outside it, they are sculpture.</p>

    <h2>Water with a memory</h2>

    <p>What distinguishes this water is that everyone knows exactly where it came from. The cooperative meters each family's share, posts the ridge's daily yield beside the bus schedule, and settles arguments about olive trees with a ledger rather than a lawsuit. Scarcity, managed openly, has produced the opposite of the hoarding everyone predicted — a small civics of condensation.</p>

    <p>By eight the sun burns through, the fog lifts, and the nets stand slack until evening. The founder walks the line once more, thumbing the gutters clear, and says the thing she apparently says to every visiting journalist, because it is true: the sky did not stop giving them water. It just stopped delivering. Now they pick it up themselves.</p>

